#!/usr/bin/env python
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import List

METHODS = ["single_lora", "average", "task_arithmetic", "ties", "dare", "della", "breadcrumbs", "optmerge", "mirage"]
TASKS = ["TextVQA", "ChartQA", "DocVQA", "ScienceQA", "GQA", "MathVista"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Create LaTeX result table from simple JSON results.")
    parser.add_argument("--result-dir", required=True)
    parser.add_argument("--output", required=True)
    return parser.parse_args()


def load_score(result_dir: Path, method: str, task: str) -> str:
    # Expected optional simple file format:
    # results/raw/mirage.json = {"TextVQA": 55.1, "ChartQA": 62.0, ...}
    path = result_dir / f"{method}.json"
    if not path.exists():
        return "--"
    try:
        with path.open("r", encoding="utf-8") as f:
            data = json.load(f)
        val = data.get(task, data.get(task.lower(), None))
        if val is None:
            return "--"
        return f"{float(val):.2f}"
    except Exception:
        return "--"


def method_name(method: str) -> str:
    if method == "mirage":
        return r"\textbf{MIRAGE}"
    if method == "single_lora":
        return "Single-task LoRA"
    return method.replace("_", " ").title()


def main() -> None:
    args = parse_args()
    result_dir = Path(args.result_dir)
    lines: List[str] = []
    nl = r"\\"
    lines.append("% Auto-generated by scripts/make_tables.py")
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    lines.append(r"\small")
    lines.append(r"\begin{tabular}{lcccccccc}")
    lines.append(r"\toprule")
    lines.append("Method & TextVQA & ChartQA & DocVQA & ScienceQA & GQA & MathVista & Avg. & Retention " + nl)
    lines.append(r"\midrule")
    for method in METHODS:
        scores = [load_score(result_dir, method, task) for task in TASKS]
        nums = [float(s) for s in scores if s != "--"]
        avg = f"{sum(nums)/len(nums):.2f}" if nums else "--"
        retention = "100.0" if method == "single_lora" else "--"
        name = method_name(method)
        if method == "mirage" and avg != "--":
            avg = rf"\textbf{{{avg}}}"
        lines.append(f"{name} & " + " & ".join(scores) + f" & {avg} & {retention} " + nl)
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\caption{Main results. All numbers are placeholders until experiments are completed. Retention is normalized against the corresponding single-task LoRA adapters.}")
    lines.append(r"\label{tab:main_results}")
    lines.append(r"\end{table*}")

    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
